create extension if not exists pgcrypto;

create type public.product_availability as enum ('available', 'check', 'preorder', 'unavailable');
create type public.order_status as enum ('received', 'to_check', 'awaiting_confirmation', 'confirmed', 'preparing', 'in_delivery', 'delivered', 'cancelled');

create table public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'admin', 'customer')),
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = (select auth.uid()) and role in ('owner', 'admin')
  );
$$;

create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = (select auth.uid()) and role = 'owner'
  );
$$;

create table public.products (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null check (length(title) between 2 and 140),
  description text not null default '',
  category text not null,
  image_urls text[] not null default '{}',
  price_usd numeric(12,2) not null check (price_usd >= 0),
  price_cdf numeric(14,2) check (price_cdf is null or price_cdf >= 0),
  sizes text[] not null default '{}',
  colors text[] not null default '{}',
  availability public.product_availability not null default 'check',
  promo_label text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text,
  email text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_supplier_details (
  product_id uuid primary key references public.products(id) on delete cascade,
  supplier_id uuid references public.suppliers(id) on delete set null,
  purchase_price numeric(14,2),
  supplier_availability text,
  lead_time text,
  internal_notes text,
  updated_at timestamptz not null default now()
);

create table public.store_settings (
  id smallint primary key default 1 check (id = 1),
  usd_cdf_rate numeric(14,2) check (usd_cdf_rate is null or usd_cdf_rate > 0),
  updated_at timestamptz not null default now()
);
insert into public.store_settings (id, usd_cdf_rate) values (1, null) on conflict (id) do nothing;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  phone text not null,
  city text not null,
  notes text not null default '',
  contact_consent_at timestamptz not null default now(),
  status public.order_status not null default 'received',
  currency text not null check (currency in ('USD', 'CDF')),
  exchange_rate_snapshot numeric(14,2),
  total numeric(14,2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity between 1 and 20),
  size text not null default '',
  color text not null default '',
  unit_price numeric(14,2) not null check (unit_price >= 0),
  line_total numeric(14,2) not null check (line_total >= 0)
);

create table public.order_status_history (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  old_status public.order_status,
  new_status public.order_status not null,
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);

create table public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  consented_at timestamptz not null,
  created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

